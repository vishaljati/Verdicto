import mongoose from 'mongoose'
import { Verdict } from '../models/verdict.models.js'
import { DebateSession } from "../models/debateSession.models.js"
import { ApiError, ApiResponse, AsyncHandler } from "../utils/index.js"
import PDFDocument from "pdfkit";

const getVerdict =AsyncHandler( async (req, res) => {
  try {
    const userId = req.user._id;
    const { sessionId } = req.params.id;

    const session = await DebateSession.findOne({
      _id: sessionId,
      user: userId,
    });

    if (!session) {
      throw new ApiError(404,"Session not found");
      
    }

    if (session.status !== "completed") {
      return res.status(409).json({
        success: false,
        message: "Verdict not ready",
        status: session.status,
      });
    }

    const verdict = await Verdict.findOne({ debateSession: sessionId });

    if (!verdict) {
      throw new ApiError(404,"Verdict not found");
      
    }

    return res.status(200).json(new ApiResponse(200,{verdict},"Verdict fetched successfully"));
  } catch (err) {
    console.error("Get verdict error:", err);
    return res.status(500).json({ success: false, message: "Failed to fetch verdict" });
  }
})

const exportVerdict = AsyncHandler(async (req, res) => {
    try {
        const userId = req.user._id;
        const { sessionId } = req.params;
        const format = "pdf"

        const session = await DebateSession.findOne({
            _id: sessionId,
            user: userId,
        });

        if (!session) {
            throw new ApiError(500, "Session not found");

        }

        const verdict = await Verdict.findOne({ debateSession: sessionId });
        if (!verdict) {
            throw new ApiError(500, "Verdict not found");

        }

        // ---------- PDF EXPORT ----------
        if (format === "pdf") {
            const doc = new PDFDocument({ margin: 50 });

            res.setHeader("Content-Type", "application/pdf");
            res.setHeader(
                "Content-Disposition",
                `attachment; filename=verdict-${sessionId}.pdf`
            );

            doc.pipe(res);

            // Title
            doc
                .fontSize(20)
                .text("Verdict Report", { align: "center" })
                .moveDown();

            doc
                .fontSize(12)
                .text(`Generated by Verdicto`)
                .moveDown();

            // Summary
            doc.fontSize(14).text("Summary", { underline: true });
            doc.fontSize(11).text(verdict.summary).moveDown();

            // Recommendation
            doc.fontSize(14).text("Recommendation", { underline: true });
            doc.fontSize(11).text(verdict.recommendation).moveDown();

            // Confidence
            doc.fontSize(14).text("Confidence Score", { underline: true });
            doc.fontSize(11).text(`${Math.round(verdict.confidenceScore * 100)}%`).moveDown();

            // Helper to render bullet lists
            const renderList = (title, items) => {
                doc.fontSize(14).text(title, { underline: true });
                doc.moveDown(0.5);
                items.forEach((item) => {
                    doc.fontSize(11).text(`• ${item}`);
                });
                doc.moveDown();
            };

            renderList("Pros", verdict.pros);
            renderList("Cons", verdict.cons);
            renderList("Risks", verdict.risks);
            renderList("Next Actions", verdict.nextActions);

            doc.end();
            return;
        }

        // ---------- INVALID FORMAT ----------
        return res.status(400).json(new ApiResponse(400,{},"Invalid export format. Use json or pdf."));
    } catch (err) {
        console.error("Export verdict error:", err);
        return res.status(500).json({ success: false, message: "Failed to export verdict" });
    }
})

export { getVerdict , exportVerdict }